// Turns tools/puzzles.json into public/puzzles.js (lightly scrambled so the
// answer is not readable in "view source"). Run: node tools/encode.mjs
import { readFileSync, writeFileSync } from "node:fs";
const KEY = "somewhere";
const list = JSON.parse(readFileSync(new URL("./puzzles.json", import.meta.url)));
const enc = (obj) => {
  const bytes = Buffer.from(JSON.stringify(obj), "utf8");
  for (let i = 0; i < bytes.length; i++) bytes[i] ^= KEY.charCodeAt(i % KEY.length);
  return bytes.toString("base64");
};
const out = `// Generated by tools/encode.mjs from tools/puzzles.json. Do not edit by hand.
export const PUZZLES = ${JSON.stringify(list.map(enc), null, 1)};
`;
writeFileSync(new URL("../public/puzzles.js", import.meta.url), out);
console.log(`Wrote ${list.length} puzzles to public/puzzles.js`);
