// Turns tools/puzzles.json into lib/puzzle-data.mjs, which only the server (Netlify Functions)
// reads. The answers never go to the browser: the server sends each riddle's answer only after
// that riddle's guess is in. Run after editing puzzles.json: npm run encode
import { readFileSync, writeFileSync } from "node:fs";
const list = JSON.parse(readFileSync(new URL("./puzzles.json", import.meta.url)));
const out = `// Generated by tools/encode.mjs from tools/puzzles.json. Do not edit by hand.
// Server only: never import this from public/.
export default ${JSON.stringify(list)};
`;
writeFileSync(new URL("../lib/puzzle-data.mjs", import.meta.url), out);
console.log(`Wrote ${list.length} puzzles to lib/puzzle-data.mjs`);
